namespace Reflections
{
    /// <summary>
    /// Product class
    /// </summary>
    internal class Product
    {
        /// <summary>
        /// Gets or sets id
        /// </summary>
        /// <value>
        /// Id of the product
        /// </value>
        public int Id { get; set; } = 101;

        /// <summary>
        /// Gets or sets title
        /// </summary>
        /// <value>
        /// Title of the product
        /// </value>
        public string Title { get; set; } = "Laptop";

        /// <summary>
        /// Gets or sets price
        /// </summary>
        /// <value>
        /// Price of the product
        /// </value>
        public double Price { get; set; } = 999.99;
    }
}
